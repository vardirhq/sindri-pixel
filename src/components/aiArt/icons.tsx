export type IconName = keyof typeof GLYPHS;

const pathCache = new Map<IconName, string>();

function glyphPath(name: IconName): string {
  let d = pathCache.get(name);
  if (!d) {
    d = '';
    GLYPHS[name].forEach((row, y) => {
      // Merge horizontal runs into one rect each.
      for (let x = 0; x < row.length; x++) {
        if (row[x] !== '#') continue;
        let end = x;
        while (row[end + 1] === '#') end++;
        d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
        x = end;
      }
    });
    pathCache.set(name, d);
  }
  return d;
}

export function Icon({ name, size = 12 }: { name: IconName; size?: number }) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={glyphPath(name)} fill="currentColor" />
    </svg>
  );
}
